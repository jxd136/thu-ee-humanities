  /* 组合生成：从上面各槽位随机取词填进范式 */
  function mulberry32(a) {
    return function () {
      a = (a + 0x6d2b79f5) >>> 0;
      let t = a;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }
  const hashStr = (s) => {
    let h = 2166136261;
    for (let i = 0; i < s.length; i++) { h ^= s.charCodeAt(i); h = Math.imul(h, 16777619); }
    return h >>> 0;
  };

  function makeEssay(seed) {
    const rng = mulberry32(hashStr(String(seed)));
    const pick = (arr) => arr[Math.floor(rng() * arr.length) % arr.length];
    /* 偶尔给主语加一层定语，插在模板层面，保证句子结构不乱 */
    const fill = (tpl) => {
      let s = tpl;
      if (rng() < 0.3 && s.indexOf('{X}') >= 0) {
        /* 定语放名词前面：「一种尚未被命名的主体性」「那些结构性的时代命题」 */
        const pre = rng() < 0.5 ? pick(['一种', '某种', '那些', '一种并不'] ) : '';
        s = s.replace('{X}', pre + pick(ESSAY.attr) + '{X}');
      }
      return s
        .replace(/\{X\}/g, () => pick(ESSAY.noun))
        .replace(/\{Y\}/g, () => pick(ESSAY.noun))
        .replace(/\{Z\}/g, () => pick(ESSAY.noun))
        .replace(/\{PRED\}/g, () => pick(ESSAY.pred));
    };

    const r = rng();
    /* 加框架词：已经以同一个词开头就不再叠 */
    const pre = (s, w) => (s.indexOf(w) === 0 ? s : w + '，' + s);
    let s;
    if (r < 0.3) {
      /* 开头型：段落开头 + 论点 */
      s = fill(pick(ESSAY.open));
      if (rng() < 0.35) s = pre(s, pick(ESSAY.frame));
    } else if (r < 0.72) {
      /* 论证型：[框架，] 论点 [，连接 + 论点] */
      s = fill(pick(ESSAY.arg));
      if (rng() < 0.4) s = pre(s, pick(ESSAY.frame));
      if (rng() < 0.35) s += '，' + pick(ESSAY.link) + '，' + fill(pick(ESSAY.arg));
    } else {
      /* 结论型：用与「因此」不冲突的框架词 */
      s = fill(pick(ESSAY.close));
      if (rng() < 0.4) s = pre(s, pick(ESSAY.closeFrame));
    }

    /* 收尾：把所有标点问题一次性收拾干净 */
    const tidy = (x) => x
      .replace(/[，。、；：]{2,}/g, '，')     /* 连续标点合成一个 */
      .replace(/^[，。、；：\s]+/, '')        /* 去首标点 */
      .replace(/[，。、；：\s]+$/, '')        /* 去尾标点 */
      .replace(/([，。])(因此|所以|总而言之|概而言之|尽管如此|恰恰相反|也正因此)(?=[，。])/g, '$1')
      .replace(/([，。])(因此|所以|总而言之|概而言之|尽管如此)(?=[^\s，。、；：])/g, '$1$2，');
    s = tidy(s);
    /* 同一个框架词在一句里出现两次，去掉后面那个 */
    ['在这个意义上', '归根结底', '概而言之', '由此可见', '因此', '恰恰相反', '也正因此'].forEach((w) => {
      const first = s.indexOf(w);
      if (first < 0) return;
      const second = s.indexOf(w, first + w.length);
      if (second > 0) s = tidy(s.slice(0, second) + s.slice(second + w.length));
    });
    s = tidy(s);

    if (s.length > 42) {
      const cut = s.slice(0, 42);
      const lastP = Math.max(cut.lastIndexOf('，'), cut.lastIndexOf('；'));
      s = tidy(lastP > 18 ? cut.slice(0, lastP) : cut);
    }
    return s;
  }

